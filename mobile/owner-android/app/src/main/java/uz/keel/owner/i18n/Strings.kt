package uz.keel.owner.i18n

import uz.keel.design.Lang

// The application's own words, in the three languages a restaurant here is run
// in.
//
// ⚠️ **Its own dictionary rather than the panel's, and that was measured on the
// waiter build**: importing the admin dictionary cost 500 KB of bundle to use
// about sixty strings. What is worth sharing is the *rules*; wording for screens
// that exist only here is this application's own text.
//
// ⚠️ **Data classes with named arguments, not a map.** A map makes a missing key
// a blank line in front of a Russian-speaking owner; this makes it a compile
// error — the property the TypeScript original had from `Dict = typeof uz`, and
// the reason this file is verbose.
//
// ⚠️ Generated once from `mobile/owner/src/i18n.ts` and then owned here: the
// wording is the Expo build's, so the two applications say the same thing in the
// same words while both exist.

data class Dict(
    val lang: String,
    val appName: String,
    val server: Server,
    val login: Login,
    val tabs: Tabs,
    val today: Today,
    val who: Who,
    val alerts: Alerts,
    val orders: Orders,
    val feedback: Feedback,
    val reports: Reports,
    val check: Check,
    val money: Money,
    val settings: Settings,
    val support: Support,
    val offline: Offline,
    val notice: Notice,
    val common: Common,
) {
    data class Server(
    val title: String,
    val hint: String,
    val placeholder: String,
    val next: String,
    val bad: String,
    )
    data class Login(
    val title: String,
    val username: String,
    val password: String,
    val submit: String,
    val other: String,
    val failed: String,
    )
    data class Tabs(
    val today: String,
    val alerts: String,
    val orders: String,
    val feedback: String,
    val reports: String,
    val settings: String,
    )
    data class Today(
    val title: String,
    val revenue: String,
    val orders: String,
    val average: String,
    val delivered: String,
    val cancelled: String,
    val vsYesterday: (Int) -> String,
    val noYesterday: String,
    val branchAll: String,
    val briefing: String,
    val briefingLocked: String,
    val updated: (String) -> String,
    )
    data class Who(
    val title: String,
    val now: (Int) -> String,
    val absent: (Int) -> String,
    val nobody: String,
    val since: (String) -> String,
    val done: (String, String) -> String,
    val notYet: String,
    val off: String,
    val empty: String,
    )
    data class Alerts(
    val title: String,
    val empty: String,
    val emptyHint: String,
    val pendingOrders: (Int) -> String,
    val preorders: (Int) -> String,
    val reservations: (Int) -> String,
    val posUnaccepted: (Int) -> String,
    val posFailed: (Int) -> String,
    val posUnmapped: (Int) -> String,
    val printFailed: (Int) -> String,
    val kinds: Map<String, String>,
    val lossTitle: String,
    val lossEmpty: String,
    val by: (String) -> String,
    /** The check number and the table, whichever are known. */
    val checkRef: (String, String) -> String,
    )
    data class Orders(
    val title: String,
    val empty: String,
    val emptyHint: String,
    val confirm: String,
    val cancel: String,
    val call: String,
    val cancelReason: String,
    val cancelDo: String,
    val cancelBack: String,
    val failed: String,
    val ago: (String) -> String,
    )
    data class Feedback(
    val title: String,
    val average: (String) -> String,
    val filterOpen: String,
    val filterLow: String,
    val filterAll: String,
    val empty: String,
    val emptyAll: String,
    val emptyHint: String,
    val call: String,
    val answer: String,
    val answerHint: String,
    val answerPlaceholder: String,
    val answerDo: String,
    val answered: (String) -> String,
    val failed: String,
    )
    data class Reports(
    val title: String,
    val today: String,
    val week: String,
    val month: String,
    val revenue: String,
    val orders: String,
    val average: String,
    val topDishes: String,
    val staff: String,
    val hours: (String) -> String,
    val owed: String,
    val stock: String,
    val stockEmpty: String,
    val empty: String,
    )
    data class Check(
    val title: (String) -> String,
    val titleEmpty: String,
    val table: (String) -> String,
    val guests: (Int) -> String,
    val open: String,
    val closedAt: (String) -> String,
    val cancelled: String,
    val refunded: String,
    val split: String,
    val noLines: String,
    val subtotal: String,
    val discount: String,
    val discountBy: (String) -> String,
    val approvedBy: (String) -> String,
    val service: (Int) -> String,
    val total: String,
    val payment: String,
    val methods: Map<String, String>,
    val refundTitle: String,
    val voided: (String) -> String,
    val voidAfterBill: String,
    val wasted: String,
    val openedBy: (String, String) -> String,
    val server: (String) -> String,
    val precheck: (String) -> String,
    val closedBy: (String) -> String,
    val fiscalError: String,
    val fiscalSign: (String) -> String,
    val notFound: String,
    )
    data class Money(
    val title: String,
    val entryHint: String,
    val intro: String,
    val cash: String,
    val cashHint: String,
    val bank: String,
    val bankHint: String,
    val rails: String,
    val railsHint: String,
    val nothingHere: String,
    val counted: String,
    val summed: String,
    /** Names for the places the server words in Uzbek. */
    val kinds: Map<String, String>,
    val openedBy: (String) -> String,
    val settledThrough: (String) -> String,
    val overLimit: (String, String) -> String,
    val bankTitle: String,
    val bankFormHint: String,
    val account: String,
    val balance: String,
    val save: String,
    val saved: String,
    val failed: String,
    )
    data class Settings(
    val title: String,
    val language: String,
    val theme: String,
    val themeSystem: String,
    val themeLight: String,
    val themeDark: String,
    val plan: String,
    val planNone: String,
    val planNoneHint: String,
    val planMonthly: String,
    val planIndividual: String,
    val planUntil: (String) -> String,
    val planDaysLeft: (Int) -> String,
    val planDueToday: String,
    val planOverdue: (Int) -> String,
    val planNoDate: String,
    val help: String,
    val helpHint: String,
    val account: String,
    val branch: String,
    val restaurant: String,
    val version: String,
    val signOut: String,
    val changeServer: String,
    val changeServerHint: String,
    val notifications: String,
    val push: Map<String, String>,
    val pushHint: Map<String, String>,
    )
    data class Support(
    val title: String,
    val lead: String,
    val searchPlaceholder: String,
    val found: String,
    val noAnswer: String,
    val askOperator: String,
    val history: String,
    val placeholder: String,
    val you: String,
    val operator: String,
    val assistant: String,
    val waiting: String,
    val answered: String,
    val closed: String,
    val failed: String,
    /** ⚠️ The base could not be fetched — which is not "no answer exists".
     *  Saying "nothing found" for that sends somebody away satisfied that
     *  their question has no answer, when the truth is that this phone has
     *  nothing to look in. */
    val baseUnavailable: String,
    )
    data class Offline(
    val title: String,
    val body: String,
    val retrying: (Int) -> String,
    )
    data class Notice(
    val ok: String,
    )
    /** ⚠️ Its own type, not a map of strings: three of these four are functions,
     *  and a map would have made them the one thing a dictionary cannot hold. */
    data class TimeAgo(
        val now: String,
        val min: (Int) -> String,
        val hour: (Int) -> String,
        val day: (Int) -> String,
    )

    data class Common(
    val retry: String,
    val loading: String,
    val close: String,
    val loadFailed: String,
    val timeAgo: TimeAgo,
    )
}

