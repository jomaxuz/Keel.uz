package uz.keel.guest.i18n

import uz.keel.design.Lang

// Every word this application says on its own behalf.
//
// ⚠️ **A typed dictionary rather than string resources**, exactly as the five
// staff applications do it: a missing key is a compile error here and a blank
// space on the screen there. In an application a guest sees, a blank space is
// the restaurant looking unfinished.
//
// ⚠️ **Uzbek is the base and all three are written together.** A language added
// later is a language that stays half-done — the lesson `lib/i18n/growth.ts`
// paid for on the web side.
//
// ⚠️ **The restaurant's own words are not here.** Dish names, category names and
// descriptions come from the panel in whatever languages the owner filled in,
// and fall back to Uzbek (`Named.pick`). Text an owner typed can never come out
// of a dictionary we ship — and neither can a refusal the server wrote: those
// arrive already translated (`middleware.Lang`), which is why the API sends
// `Accept-Language` on every request.

data class Dict(
    /** This language, named in itself — "Русский", never "Ruscha". */
    val lang: String,
    val tabs: Tabs,
    val menu: Menu,
    val dish: Dish,
    val cart: Cart,
    val checkout: Checkout,
    val map: MapPick,
    val order: Order,
    val account: Account,
    val common: Common,
) {
    data class Account(
        val title: String,
        val signIn: String,
        val signInHint: String,
        val phone: String,
        val name: String,
        val code: String,
        val codeSent: (String) -> String,
        /** ⚠️ **Said plainly, or a code on screen looks like a bug.** The
         *  restaurant has not connected an SMS gateway yet, so the server hands
         *  the code back instead of sending it. */
        val demoNote: (String) -> String,
        val sendCode: String,
        val resend: String,
        val resendIn: (Int) -> String,
        val verify: String,
        val signOut: String,
        val points: String,
        val pointsHint: (String) -> String,
        val favorites: String,
        val noFavorites: String,
        val myOrders: String,
        val language: String,
        val theme: String,
        val themeSystem: String,
        val themeLight: String,
        val themeDark: String,
        val notifications: String,
        val notificationsOn: String,
        val notificationsOff: String,
        val notificationsAsk: String,
        // ---- Settings ----
        //
        // ⚠️ **One section rather than scattered rows.** Language sat in the
        // header and the theme sat in the middle of the account tab, and
        // everything else — the name the kitchen prints on the order, the
        // addresses the checkout offers — could only be changed by ordering
        // again. A setting nobody can find is a setting that does not exist.
        val settings: String,
        val profile: String,
        val firstName: String,
        val lastName: String,
        val save: String,
        val saved: String,
        val addresses: String,
        val noAddresses: String,
        val addressHint: String,
        val deleteAddress: String,
        val about: String,
        val version: (String) -> String,
        val failed: String,
    )

    data class Tabs(
        val menu: String,
        val cart: String,
        val orders: String,
        val account: String,
    )

    data class Menu(
        /** ⚠️ **There is no home page and this is the first thing on screen.**
         *  A restaurant application opened by somebody who is hungry has one
         *  job, and a landing page is a tap between them and it. */
        val search: String,
        val searchEmpty: (String) -> String,
        val all: String,
        val soldOut: String,
        val closed: String,
        val closedHint: String,
        val empty: String,
        val loadFailed: String,
        val retry: String,
    )

    data class Dish(
        val add: String,
        val comment: String,
        val commentHint: String,
        /** ⚠️ Phrased as the instruction it is, never as "required": a label
         *  that names a rule leaves somebody looking for what to do about it. */
        val choose: String,
        val chooseMany: String,
        val needsChoice: (String) -> String,
    )

    data class Cart(
        val title: String,
        val empty: String,
        val emptyHint: String,
        val subtotal: String,
        val checkout: String,
        val clear: String,
        /** ⚠️ Its own action beside the stepper, as on the site: minus-to-zero
         *  works, but somebody who wants the dish gone looks for this. */
        val remove: String,
        /** A note for one dish — the kitchen reads it off the order. */
        val itemComment: String,
        val summary: String,
        val items: (Int) -> String,
        val delivery: String,
        /** ⚠️ **The fee is named and deferred, never shown as zero.** A basket
         *  that prints "Yetkazib berish: 0" is quoting a price nobody has
         *  calculated — the zones are the server's and the address is not
         *  known yet. */
        val atCheckout: String,
        val total: String,
        val keepShopping: String,
        // ---- Signed out ----
        // ⚠️ The basket is behind the sign-in now: a restaurant wants the order
        // attached to somebody it can ring back.
        val signInTitle: String,
        val signInHint: String,
        val signInAction: String,
    )

    data class Checkout(
        val title: String,
        val delivery: String,
        val pickup: String,
        val dinein: String,
        val name: String,
        val phone: String,
        val address: String,
        val addressPick: String,
        /** ⚠️ Offered before the map, never after: somebody who orders to the
         *  same flat every week should be one tap from done. */
        val savedAddresses: String,
        val newAddress: String,
        val saveAddress: String,
        val addressHint: String,
        val comment: String,
        val payment: String,
        val payCash: String,
        val payCard: String,
        val promo: String,
        val subtotal: String,
        val discount: String,
        val deliveryFee: String,
        val total: String,
        val points: (String) -> String,
        val pointsEarn: (String) -> String,
        val minOrder: (String) -> String,
        val notDelivered: String,
        val soldOut: (String) -> String,
        val send: String,
        val nameNeeded: String,
        val phoneNeeded: String,
        val addressNeeded: String,
        val failed: String,
    )

    /** The address picker's own words. One step of the checkout — a guest never
     *  opens it for its own sake. */
    data class MapPick(
        val title: String,
        val search: String,
        val myLocation: String,
        val confirm: String,
        val noKey: String,
        val denied: String,
    )

    data class Order(
        val title: String,
        val number: (String) -> String,
        val pending: String,
        val confirmed: String,
        val preparing: String,
        val onTheWay: String,
        val delivered: String,
        val cancelled: String,
        val none: String,
        val noneHint: String,
        val payNow: String,
        val loadFailed: String,
        val placed: String,
        /** Over the map while the order is on its way. */
        val courierComing: (String) -> String,
        val callCourier: String,
        /** When the courier's phone last reported, e.g. "3 daqiqa oldin". */
        val courierSeen: (Int) -> String,
    )

    data class Common(
        val ok: String,
        val retry: String,
        val loading: String,
        val back: String,
        val close: String,
    )
}

