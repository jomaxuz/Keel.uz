package uz.keel.team.i18n

import uz.keel.design.Lang

// The application's own words, in the three languages a restaurant here is run
// in.
//
// ⚠️ **Its own dictionary rather than the panel's**, measured on the Expo build:
// importing the admin dictionary cost about 500 KB to use sixty strings. What is
// worth sharing is the *rules* — and where a word names a meaning defined
// elsewhere it is not redefined here. The day statuses are the example: their
// colours come from the shared `StatusColor`, so a shift that is amber in the
// office cannot be green on a phone. Only the label is local.
//
// ⚠️ **Data classes with named arguments, not a map.** A missing key would be a
// blank line in front of a Russian-speaking cook; this makes it a compile error.

data class Dict(
    val lang: String,
    val appName: String,
    val server: Server,
    val login: Login,
    val tabs: Tabs,
    val clock: Clock,
    val profile: Profile,
    val buy: Buy,
    val zakup: Zakup,
    val sklad: Sklad,
    val sanoq: Sanoq,
    val settings: Settings,
    val push: Push,
    val offline: Offline,
    val common: Common,
) {
    data class Server(
        val title: String,
        val hint: String,
        val placeholder: String,
        val next: String,
        val bad: String,
    )

    data class Login(
        val title: String,
        val username: String,
        val password: String,
        val submit: String,
        val other: String,
        val failed: String,
    )

    data class Tabs(
        val profile: String,
        val buy: String,
        val zakup: String,
        /** ⚠️ **A tab exists only for the account that may use it.** Issuing
         *  from the store is one job in a restaurant, and a cook shown a screen
         *  that would refuse them learns to stop reading the app. */
        val sklad: String,
        /** ⚠️ Counting is its own permission (`stock`), and the tab is drawn
         *  only for the account that carries it — the shipped Texnolog role. */
        val sanoq: String,
        val settings: String,
    )

    data class Clock(
        val start: String,
        val end: String,
        /** ⚠️ Named plainly rather than as a failure: refusing is a choice, and
         *  the way back is the system settings, which is what this says. */
        val needLocation: String,
        val failed: String,
    )

    data class Profile(
        val title: String,
        val today: String,
        val week: String,
        val month: String,
        val worked: String,
        val expected: String,
        val diff: String,
        val onShift: String,
        val calendar: String,
        val hour: String,
        val minute: String,
        val noData: String,
        val loadFailed: String,
        /** ⚠️ Read beside coloured squares, so each is a phrase somebody can act
         *  on rather than a category name. */
        val status: Map<String, String>,
    )

    data class Buy(
        val purse: String,
        val purseOwed: String,
        val purseOf: (String, String) -> String,
        val orderTitle: (String) -> String,
        val orderFrom: (String) -> String,
        val asked: (String, String) -> String,
        val got: String,
        val changed: String,
        val noneLeft: String,
        val wasMissing: String,
        val undo: String,
        val finish: String,
        val shortTitle: String,
        val nothingShort: String,
        val basketTitle: String,
        val addTitle: String,
        val searchPlaceholder: String,
        val addNew: (String) -> String,
        val onHand: (String, String) -> String,
        val need: (String, String) -> String,
        val qty: (String) -> String,
        val price: String,
        /** ⚠️ The only guard this figure has. */
        val lastPrice: (String) -> String,
        val whereTitle: String,
        val wherePlaceholder: String,
        val total: String,
        val send: String,
        val sendHint: String,
        val sent: (String) -> String,
        val alreadySent: String,
        val nothingToSend: String,
        val created: (String) -> String,
        val loadFailed: String,
        val sendFailed: String,
    )

    data class Zakup(
        val forDate: String,
        val listTitle: String,
        val qty: String,
        val shortTitle: String,
        val search: String,
        val unitIs: (String) -> String,
        val nothingShort: String,
        val addNew: (String) -> String,
        val onHand: (String, String) -> String,
        val need: (String, String) -> String,
        val review: String,
        val previewTitle: String,
        val previewBody: (String) -> String,
        val back: String,
        val send: String,
        val sent: (Int) -> String,
        val sentTitle: String,
        val statusSent: String,
        val statusShipped: String,
        val statusDone: String,
        val progress: (Int, Int) -> String,
        val loadFailed: String,
        val sendFailed: String,
        // ---- Where each line goes ----
        // ⚠️ Shown, never chosen here: the catalogue decides, but a line filed
        // wrongly otherwise sits all morning on a phone belonging to somebody
        // who was never going to answer it.
        val fromMarket: String,
        val fromStore: String,
        val splitNote: (Int, Int) -> String,
        val sentSplit: (Int, Int) -> String,
        // ---- Counting what turned up ----
        val accept: String,
        val acceptTitle: String,
        val acceptBody: String,
        val acceptSend: String,
        val accepted: String,
    )

    /** Handing out what a request asks for.
     *
     *  ⚠️ **Its own screen rather than a mode of the buyer's**, because it is a
     *  different act: a buyer writes prices at a stall, a storekeeper takes
     *  things off a shelf. Sharing one screen would put every buying price in
     *  the building in front of whoever counts the fridge. */
    data class Sklad(
        val title: String,
        val empty: String,
        val asked: (String) -> String,
        val give: String,
        val none: String,
        val undo: String,
        val ship: String,
        val shipped: String,
        val noneGiven: String,
        val loadFailed: String,
        val sendFailed: String,
    )

    /** Counting the store.
     *
     *  ⚠️ **Nothing here names an expected figure, because the screen never has
     *  one to name.** The server stopped sending it (handlers/stocktake.go): a
     *  sheet that says "there should be 9.4 kg" beside an empty box is a sheet
     *  that gets 9.4 written into it. The words that do speak of it —
     *  `savedTotal`, `countedVs` — belong to what comes back after the count is
     *  written, where it is a finding rather than a target. */
    data class Sanoq(
        val title: String,
        val store: String,
        val mainStore: String,
        val search: String,
        val onlyLeft: String,
        val progress: (Int, Int) -> String,
        val qtyHint: String,
        /** ⚠️ What the count is measured from. Without it the variance reads as
         *  a running balance the system has been keeping, which it is not. */
        val since: (String) -> String,
        val neverCounted: String,
        val empty: String,
        val allDone: String,
        val notePlaceholder: String,
        val save: (Int) -> String,
        val savedTitle: String,
        val savedTotal: String,
        val noDiff: String,
        val countedVs: (String, String) -> String,
        val loadFailed: String,
        val sendFailed: String,
    )

    data class Settings(
        val title: String,
        val language: String,
        val theme: String,
        val themeSystem: String,
        val themeLight: String,
        val themeDark: String,
        val account: String,
        val notifications: String,
        val restaurant: String,
        val signOut: String,
        val changeServer: String,
        val changeServerHint: String,
        val version: String,
    )

    data class Push(
        val working: String,
        val asking: String,
        val denied: String,
        val failed: String,
        val hintWorking: String,
        val hintAsking: String,
        val hintDenied: String,
        val hintFailed: String,
    )

    data class Offline(val title: String, val body: String, val retrying: (Int) -> String)

    data class Common(
        val retry: String,
        val loading: String,
        val cancel: String,
        val close: String,
        val ok: String,
    )
}

