// Staff screens follow the same `lang` cookie as the customer site, so the
// language a manager picks on the site carries over to the panel.
export function useAdminT(): AdminDict {
  const { lang } = useI18n();
  if (lang === "ru") return adminRu;
  if (lang === "en") return adminEn;
  return adminUz;
}
